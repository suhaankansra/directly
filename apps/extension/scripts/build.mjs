/**
 * Build the extension into two targets:
 *
 *   dist/chrome   — loads unpacked in Chrome / Edge / Brave / Arc, and is also
 *                   the input for Safari's `safari-web-extension-converter`
 *   dist/firefox  — `web-ext run` or about:debugging → Load Temporary Add-on
 *
 * Manifests are generated here so both targets share one source of truth, and
 * so the permission list is visible in exactly one place.
 */

import { copyFile, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as esbuild from 'esbuild';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const dist = path.join(root, 'dist');

const pkg = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'));
const version = pkg.version ?? '0.1.0';

const ICONS = {
  16: 'icons/icon16.png',
  32: 'icons/icon32.png',
  48: 'icons/icon48.png',
  128: 'icons/icon128.png',
};

const DESCRIPTION =
  'Instagram, DMs only: no feed, no Reels, no Explore. Watch the reel a friend sent, then stop.';

function baseManifest() {
  return {
    manifest_version: 3,
    name: 'Only Inbox',
    short_name: 'Only Inbox',
    version,
    description: DESCRIPTION,
    icons: ICONS,
    // `tabs` is deliberately absent: tabs.update()/onRemoved need no permission,
    // and asking for less is both true and easier to justify in review.
    permissions: ['storage', 'webNavigation'],
    host_permissions: ['https://www.instagram.com/*', 'https://instagram.com/*'],
    action: {
      default_title: 'Only Inbox',
      default_popup: 'popup.html',
      default_icon: ICONS,
    },
    options_ui: { page: 'popup.html', open_in_tab: true },
    content_scripts: [
      {
        matches: ['https://www.instagram.com/*', 'https://instagram.com/*'],
        js: ['content.js'],
        run_at: 'document_start',
        all_frames: false,
      },
    ],
  };
}

function chromeManifest() {
  return {
    ...baseManifest(),
    minimum_chrome_version: '116',
    background: { service_worker: 'background.js' },
  };
}

function firefoxManifest() {
  return {
    ...baseManifest(),
    // Firefox MV3 still uses an event page rather than a service worker.
    background: { scripts: ['background.js'] },
    browser_specific_settings: {
      gecko: {
        id: 'only-inbox@example.com',
        strict_min_version: '121.0',
      },
    },
  };
}

/**
 * Inline `?raw` imports (the bundled CSS lives in the JS so the same script can
 * be injected into a WKWebView, which has no manifest to declare styles in).
 * Without this the content script would inject empty stylesheets.
 */
const rawPlugin = {
  name: 'raw-text',
  setup(build) {
    build.onResolve({ filter: /\?raw$/ }, (args) => ({
      path: path.join(args.resolveDir, args.path.replace(/\?raw$/, '')),
      namespace: 'raw-text',
    }));
    build.onLoad({ filter: /.*/, namespace: 'raw-text' }, async (args) => ({
      contents: await readFile(args.path, 'utf8'),
      loader: 'text',
    }));
  },
};

async function bundle(entry, outfile) {
  await esbuild.build({
    entryPoints: [path.join(root, entry)],
    outfile,
    bundle: true,
    format: 'iife',
    target: ['chrome116', 'firefox121', 'safari15'],
    platform: 'browser',
    legalComments: 'none',
    minify: false,
    sourcemap: false,
    plugins: [rawPlugin],
  });
}

async function buildTarget(name, manifest) {
  const out = path.join(dist, name);
  await rm(out, { recursive: true, force: true });
  await mkdir(out, { recursive: true });

  await bundle('src/content.ts', path.join(out, 'content.js'));
  await bundle('src/background.ts', path.join(out, 'background.js'));
  await bundle('src/popup/popup.ts', path.join(out, 'popup.js'));

  await copyFile(path.join(root, 'src/popup/index.html'), path.join(out, 'popup.html'));
  await copyFile(path.join(root, 'src/popup/popup.css'), path.join(out, 'popup.css'));
  await copyFile(path.join(root, 'src/popup/privacy.html'), path.join(out, 'privacy.html'));

  // Icons are generated by tools/make-icons.mjs; if they are missing the build
  // still succeeds so the logic can be exercised, with a warning.
  for (const file of Object.values(ICONS)) {
    const from = path.join(root, file);
    const to = path.join(out, file);
    try {
      await mkdir(path.dirname(to), { recursive: true });
      await copyFile(from, to);
    } catch {
      console.warn(`[extension] missing ${file} — run: node tools/make-icons.mjs`);
    }
  }

  await writeFile(path.join(out, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n', 'utf8');
  return out;
}

await mkdir(dist, { recursive: true });
const chrome = await buildTarget('chrome', chromeManifest());
const firefox = await buildTarget('firefox', firefoxManifest());
console.log(`extension: built ${path.relative(process.cwd(), chrome)} and ${path.relative(process.cwd(), firefox)}`);
