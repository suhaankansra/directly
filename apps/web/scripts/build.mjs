/**
 * The site is static by design: three HTML files, one stylesheet, one small
 * script, two icons. There is nothing to compile, so "build" is a copy into
 * `dist/`, which is what gets uploaded to any static host.
 */

import { cp, mkdir, rm, stat } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const from = path.join(root, 'public');
const to = path.join(root, 'dist');

await rm(to, { recursive: true, force: true });
await mkdir(to, { recursive: true });
await cp(from, to, { recursive: true });

// The icon files live in public/assets and are generated by tools/make-icons.mjs.
try {
  await stat(path.join(to, 'assets', 'icon-192.png'));
} catch {
  console.warn('[web] assets/icon-192.png missing — run: node tools/make-icons.mjs');
}

console.log('web: copied public/ → dist/');
